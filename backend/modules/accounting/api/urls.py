from django.urls import path

from .views import (
    AccountActivateView,
    AccountClassDisableView,
    AccountClassEnableView,
    AccountClassListView,
    AccountDeactivateView,
    AccountDetailView,
    AccountListCreateView,
    ClassificationActivateView,
    ClassificationDeactivateView,
    ClassificationDetailView,
    ClassificationListCreateView,
    EntryDetailView,
    EntryListView,
    MethodDetailView,
    MethodListView,
    RegularizationApplyView,
    RegularizationPreviewView,
    SettingsView,
)

urlpatterns = [
    path('accounts/', AccountListCreateView.as_view(), name='accounting-account-list'),
    path('accounts/<uuid:account_id>/', AccountDetailView.as_view(), name='accounting-account-detail'),
    path('accounts/<uuid:account_id>/activate/', AccountActivateView.as_view(), name='accounting-account-activate'),
    path('accounts/<uuid:account_id>/deactivate/', AccountDeactivateView.as_view(),
         name='accounting-account-deactivate'),
    path('settings/', SettingsView.as_view(), name='accounting-settings'),
    path('account-classes/', AccountClassListView.as_view(), name='accounting-account-class-list'),
    path('account-classes/<str:code>/enable/', AccountClassEnableView.as_view(),
         name='accounting-account-class-enable'),
    path('account-classes/<str:code>/disable/', AccountClassDisableView.as_view(),
         name='accounting-account-class-disable'),
    path('classifications/', ClassificationListCreateView.as_view(), name='accounting-classification-list'),
    path('classifications/<uuid:classification_id>/', ClassificationDetailView.as_view(),
         name='accounting-classification-detail'),
    path('classifications/<uuid:classification_id>/activate/', ClassificationActivateView.as_view(),
         name='accounting-classification-activate'),
    path('classifications/<uuid:classification_id>/deactivate/', ClassificationDeactivateView.as_view(),
         name='accounting-classification-deactivate'),
    path('entries/', EntryListView.as_view(), name='accounting-entry-list'),
    path('entries/<uuid:entry_id>/', EntryDetailView.as_view(), name='accounting-entry-detail'),
    path('regularization/preview/', RegularizationPreviewView.as_view(), name='accounting-regularization-preview'),
    path('regularization/apply/', RegularizationApplyView.as_view(), name='accounting-regularization-apply'),
    path('payment-methods/', MethodListView.as_view(), name='accounting-method-list'),
    path('payment-methods/<str:code>/', MethodDetailView.as_view(), name='accounting-method-detail'),
]
