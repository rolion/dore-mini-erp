from datetime import datetime
from typing import Protocol

from ..domain.entities import Connection, Conversation, Message, Template


class SendResult:
    def __init__(self, provider_message_id: str):
        self.provider_message_id = provider_message_id


class MessagingGateway(Protocol):
    """Puerto de envío: un adaptador por proveedor (`WhatsAppCloudAdapter`, `FakeMessagingGateway`)."""

    def send_text(self, to: str, body: str) -> SendResult: ...
    def send_interactive(self, to: str, interactive: dict) -> SendResult: ...
    def send_template(self, to: str, name: str, language: str, components: list) -> SendResult: ...
    def list_templates(self) -> list[dict]: ...


class SecretResolver(Protocol):
    def get(self, ref: str) -> str: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class ConnectionRepository(Protocol):
    def get(self) -> Connection | None: ...
    def save(self, connection: Connection) -> Connection: ...


class ConversationRepository(Protocol):
    def get_or_create(self, connection_id, phone: str) -> Conversation: ...
    def save(self, conversation: Conversation) -> None: ...


class MessageRepository(Protocol):
    def add(self, message: Message) -> Message: ...
    def add_inbound_once(self, message: Message) -> tuple[Message, bool]: ...
    def by_provider_id(self, connection_id, wamid: str) -> Message | None: ...
    def save(self, message: Message) -> None: ...


class TemplateRepository(Protocol):
    def get(self, template_id) -> Template | None: ...
    def all(self) -> list[Template]: ...
    def replace_all(self, connection_id, rows: list[dict], now: datetime) -> list[Template]: ...
